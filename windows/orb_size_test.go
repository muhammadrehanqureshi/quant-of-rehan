package main

import (
	"math"
	"testing"
)

// Owner order 2026-11-10: the mark is the size of the orb's own source, 1.11
// times the old 13 row radius, which is the whole 14 row tile and not the ten
// percent margin of build 32. The later order of the same day asks for ten
// percent more again, and nothing else about the orb changes.
func TestOrbGrowsTenPercentAgain(t *testing.T) {
	if math.Abs(OrbGrow-1.221) > 1e-9 {
		t.Fatalf("OrbGrow is %v, want 1.221 (1.11 times 1.1)", OrbGrow)
	}
	if OrbRadius(OrbGrow) <= OrbRadius(1.11) {
		t.Fatal("the mark did not grow")
	}
}
func TestMarkTakesTheWholeTile(t *testing.T) {
	if len(orbFrames) == 0 {
		t.Skip("orbpattern.go is generated by tools/mkorb.py before the build")
	}
	th := themeAt(0)
	c := NewCanvas(38, 14, th.Panel)
	drawOrb(c, 0, 0, 38, 14, 2, OrbBurning, true, th)
	rows := map[int]bool{}
	for y := 0; y < c.H; y++ {
		for x := 0; x < c.W; x++ {
			if ce := c.Cells[y*c.W+x]; ce.Ch >= 0x2800 && ce.Ch <= 0x28ff {
				rows[y] = true
			}
		}
	}
	if len(rows) < 13 {
		t.Errorf("the mark reaches %d of the tile's 14 rows, not the source's size", len(rows))
	}
}
